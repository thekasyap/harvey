def _get_dashboard_token() -> str:
    """Reads the current token generated by Harvey Dashboard."""
    try:
        if TOKEN_FILE.exists():
            return TOKEN_FILE.read_text(encoding="ascii").strip()
    except Exception as e:
        logger.warning(f"Could not read dashboard token: {e}")
    return ""


def _create_session_cookie(user: str) -> str:
    """Creates an HMAC-signed session cookie."""
    expires_at = int(time.time()) + SESSION_DURATION_SECONDS
    payload = f"{user}:{expires_at}"
    sig = hmac.new(SESSION_SECRET, payload.encode(), hashlib.sha256).hexdigest()
    return f"{payload}:{sig}"


def _verify_session_cookie(cookie: Optional[str]) -> bool:
    """Verifies HMAC signature and expiration of the session cookie."""
    if not cookie or ":" not in cookie:
        return False
    parts = cookie.split(":")
    if len(parts) != 3:
        return False
    user, exp_str, sig = parts
    try:
        expires_at = int(exp_str)
    except ValueError:
        return False
    if time.time() > expires_at:
        return False
    payload = f"{user}:{expires_at}"
    expected_sig = hmac.new(SESSION_SECRET, payload.encode(), hashlib.sha256).hexdigest()
    return hmac.compare_digest(sig, expected_sig)


