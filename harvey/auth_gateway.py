@app.api_route("/{path:path}", methods=["GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"])
async def proxy_to_harvey(request: Request, path: str):
    if path.startswith("auth/") or path == "auth":
        raise HTTPException(status_code=404)

    token = _get_dashboard_token()
    cookie = request.cookies.get(COOKIE_NAME)
    auth_header = request.headers.get("authorization", "").strip()

    has_cookie = _verify_session_cookie(cookie)
    has_token = bool(token and auth_header == f"Bearer {token}")

    # Allow request if either session cookie or valid dashboard token is present
    if not (has_cookie or has_token):
        if request.method in ("GET", "HEAD"):
            next_param = f"?next=/{path}" if path else ""
            return RedirectResponse(f"/auth/login{next_param}", status_code=303)
        return JSONResponse({"error": "unauthorized", "message": "Session expired or invalid."}, status_code=401)

    target_url = f"{UPSTREAM_URL}/{path}"
    if request.url.query:
        target_url += f"?{request.url.query}"

    # Build upstream headers: enforce localhost loopback identity
    req_headers = dict(request.headers)
    req_headers["host"] = "localhost:5555"
    if "origin" in req_headers:
        req_headers["origin"] = "http://localhost:5555"
    if "sec-fetch-site" in req_headers:
        req_headers["sec-fetch-site"] = "same-origin"
    if token:
        req_headers["authorization"] = f"Bearer {token}"
    req_headers.pop("cookie", None)

    body = await request.body()

    async with httpx.AsyncClient(timeout=60.0) as client:
        try:
            upstream_res = await client.request(
                method=request.method,
                url=target_url,
                headers=req_headers,
                content=body,
            )
        except Exception as e:
            logger.error(f"Upstream Harvey dashboard connection error: {e}")
            return HTMLResponse(
                f"""<!DOCTYPE html>
                <html><head><title>Harvey Offline</title></head>
                <body style="background:#0d0e15;color:#e2e8f0;font-family:sans-serif;padding:40px;text-align:center;">
                  <h2>Harvey Dashboard Service is Starting or Offline</h2>
                  <p style="color:#94a3b8;margin-top:8px;">Could not connect to {UPSTREAM_URL}. The service may be starting up.</p>
                  <p style="margin-top:20px;"><button onclick="location.reload()" style="padding:10px 20px;background:#4f46e5;color:white;border:none;border-radius:6px;cursor:pointer;">Retry</button></p>
                </body></html>""",
                status_code=502,
            )

    content_type = upstream_res.headers.get("content-type", "")

    # For the root dashboard HTML, inject the token and the logout button cleanly into header-controls
    if "text/html" in content_type and path == "":
        html_text = upstream_res.text
        head_injection = f"""
        <script>
        try {{
          sessionStorage.setItem('harvey-dashboard-token', '{token}');
        }} catch(e) {{}}
        // Ensure browser fetch includes cookies for same-origin calls
        const _origFetch = window.fetch;
        window.fetch = function(url, opts) {{
          opts = opts || {{}};
          if (opts.credentials === 'omit') {{
            opts.credentials = 'same-origin';
          }}
          return _origFetch.call(this, url, opts);
        }};
        </script>
        <style>
          .btn-header-logout {{
            display: inline-flex;
            align-items: center;
            padding: 4px 10px;
            font-size: 12px;
            font-weight: 500;
            border-radius: 6px;
            border: 1px solid rgba(239, 68, 68, 0.4);
            background: rgba(239, 68, 68, 0.12);
            color: #fca5a5;
            text-decoration: none;
            cursor: pointer;
            transition: all 0.2s;
            height: 28px;
            box-sizing: border-box;
          }}
          .btn-header-logout:hover {{
            background: rgba(239, 68, 68, 0.25);
            color: #ffffff;
            border-color: rgba(239, 68, 68, 0.7);
          }}
        </style>
        """
        if "</head>" in html_text:
            html_text = html_text.replace("</head>", f"{head_injection}</head>")
        else:
            html_text = head_injection + html_text

        logout_button_html = '<a href="/auth/logout" class="btn-header-logout" title="Sign out of Harvey">Logout</a>'

        # Place the Logout button cleanly inside .header-controls right next to the refresh button
        if '<button class="refresh-btn"' in html_text:
            html_text = html_text.replace(
                '<button class="refresh-btn"',
                f'{logout_button_html}<button class="refresh-btn"',
            )
        elif '</header>' in html_text:
            html_text = html_text.replace('</header>', f'{logout_button_html}</header>')

        headers = dict(upstream_res.headers)
        headers.pop("content-length", None)
        headers.pop("content-encoding", None)
        return HTMLResponse(content=html_text, status_code=upstream_res.status_code, headers=headers)

    headers = dict(upstream_res.headers)
    headers.pop("content-length", None)
    headers.pop("content-encoding", None)

    return Response(
        content=upstream_res.content,
        status_code=upstream_res.status_code,
        headers=headers,
    )
