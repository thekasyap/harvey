@app.api_route("/auth/login", methods=["GET", "HEAD", "POST"], response_class=HTMLResponse)
async def login_page(request: Request, error: str = "", message: str = ""):
    cookie = request.cookies.get(COOKIE_NAME)
    if _verify_session_cookie(cookie):
        return RedirectResponse("/", status_code=303)
    return HTMLResponse(_render_login_html(error=error, message=message))


@app.post("/auth/send-otp")
async def send_otp():
    now = time.time()
    existing = _otp_store.get(ADMIN_EMAIL)
    if existing and now - existing.get("last_sent", 0) < 30:
        return RedirectResponse(
            "/auth/login?error=Please wait 30 seconds before requesting another code.",
            status_code=303,
        )

    code = f"{secrets.randbelow(900000) + 100000}"
    _otp_store[ADMIN_EMAIL] = {
        "code": code,
        "expires_at": now + 600,  # 10 minutes
        "last_sent": now,
    }
    logger.info(f"Generated new login OTP {code} for {ADMIN_EMAIL}")

    try:
        await _send_otp_email(ADMIN_EMAIL, code)
        logger.info(f"Successfully sent OTP email to {ADMIN_EMAIL}")
        return RedirectResponse(
            f"/auth/login?message=New code sent! Check your inbox ({ADMIN_EMAIL}).",
            status_code=303,
        )
    except Exception as e:
        logger.error(f"Failed to send OTP email: {e}")
        return RedirectResponse(
            f"/auth/login?error=Failed to send email. Check SMTP settings or use password.",
            status_code=303,
        )


@app.post("/auth/verify-otp")
async def verify_otp(otp: str = Form(...)):
    now = time.time()
    stored = _otp_store.get(ADMIN_EMAIL)
    clean_otp = otp.strip().replace(" ", "").replace("-", "")

    if not stored:
        return RedirectResponse(
            "/auth/login?error=No code was requested. Please click Send Code first.",
            status_code=303,
        )

    if now > stored["expires_at"]:
        _otp_store.pop(ADMIN_EMAIL, None)
        return RedirectResponse(
            "/auth/login?error=Verification code has expired. Please request a new one.",
            status_code=303,
        )

    if not hmac.compare_digest(stored["code"].strip(), clean_otp):
        logger.warning(f"OTP mismatch for {ADMIN_EMAIL}: entered '{clean_otp}', expected '{stored['code']}'")
        return RedirectResponse(
            "/auth/login?error=Invalid verification code. Please check your latest email and try again.",
            status_code=303,
        )

    # Valid OTP! Clear OTP and issue session cookie
    _otp_store.pop(ADMIN_EMAIL, None)
    res = RedirectResponse("/", status_code=303)
    cookie_val = _create_session_cookie(ADMIN_EMAIL)
    res.set_cookie(
        COOKIE_NAME,
        cookie_val,
        max_age=SESSION_DURATION_SECONDS,
        httponly=True,
        samesite="lax",
        secure=False,  # Allow Cloudflare SSL termination
    )
    return res


@app.post("/auth/login-password")
async def login_password(password: str = Form(...)):
    if not hmac.compare_digest(password.strip(), ADMIN_PASSWORD.strip()):
        return RedirectResponse(
            "/auth/login?error=Incorrect admin password.",
            status_code=303,
        )

    res = RedirectResponse("/", status_code=303)
    cookie_val = _create_session_cookie(ADMIN_EMAIL)
    res.set_cookie(
        COOKIE_NAME,
        cookie_val,
        max_age=SESSION_DURATION_SECONDS,
        httponly=True,
        samesite="lax",
        secure=False,
    )
    return res


@app.get("/auth/logout")
async def logout():
    res = RedirectResponse("/auth/login?message=You have been logged out.", status_code=303)
    res.delete_cookie(COOKIE_NAME)
    return res


